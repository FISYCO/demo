import { defineRecipe } from "@chakra-ui/react";

/**
 * Размер иконки — от кегля текста рядом, а не число в каждом месте (#1777).
 *
 * Иконки продукта — Outline на сетке 24 с обводкой 1.5. В размере кегля (16px при тексте 14px) обводка выходит около
 * 1px, тоньше ствола букв, и иконка читается мельче и светлее строки. На шаг крупнее она встаёт вровень с текстом:
 *
 * | Текст | Иконка |
 * |---|---|
 * | 12px (`xs`) | `xs` — 14px |
 * | 14px (`sm`) | `sm` — 18px |
 * | 16px (`md`) | `md` — 20px |
 *
 * Сравнение начертаний (Outline, Filled, Duotone) на настоящих фрагментах интерфейса — в статье Theme Tokens:
 * Filled в кнопках и списках становится тяжёлыми пятнами, Duotone выцветает, остаётся Outline нужного размера.
 */
export const iconRecipe = defineRecipe({
  className: "chakra-icon",
  variants: {
    size: {
      xs: { boxSize: "3.5" },
      sm: { boxSize: "4.5" },
      md: { boxSize: "5" },
      lg: { boxSize: "6" },
    },
  },
});
