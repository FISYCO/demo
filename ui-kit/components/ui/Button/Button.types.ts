import type { ButtonProps as BaseButtonProps } from "@chakra-ui/react";

import type { UIProps } from "../../../lib/component-types";

export type ButtonProps = UIProps<BaseButtonProps> & {
  /**
   * Сколько строк подписи показывать, дальше — многоточие (#1655).
   *
   * Нужно там, где подпись приходит извне и её длину никто не контролирует: призыв в теле статьи
   * пишет редактор, и подпись в 92 знака растягивала кнопку до 861px в колонке шириной 358, давая
   * странице горизонтальную прокрутку на телефоне.
   *
   * Свойство объявлено явно, а не прокинуто стилевым пропом: у компонентов дизайн-системы стилевые
   * пропсы срезаны `UIProps`, и это не случайность — иначе каждый потребитель правил бы вид кнопки
   * по-своему. Здесь же правка одна и описана как поведение, а не как стиль.
   */
  lineClamp?: number;
};
